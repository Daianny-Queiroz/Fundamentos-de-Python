# Solicite a temperatura para o usuário. Se estiver abaixo de 16 graus(incuindo), informe ao usuário para pegar uma blusa. Ao final escreva fim do programa 
# Entrada

temperatura = int(input("Informe uma temperatura: "))
if temperatura <= 16 : #true
    print("Coloque uma blusa de frio")
else :  #false
    print("Coloque um óculo de sol")
print()
print("Fim do programa")
